// Builds tokens/*.json (DTCG format) and css/kickoff-ui.css
// from the data in plugin/code.js, which is the single source of truth.
// Usage: node scripts/build.js
const fs = require('fs');
const path = require('path');
const root = path.join(__dirname, '..');
const src = fs.readFileSync(path.join(root, 'plugin/code.js'), 'utf8');

function grab(name) {
  const m = src.match(new RegExp('const ' + name + '=(\\[[\\s\\S]*?\\]);\\n')) || src.match(new RegExp('const ' + name + '=(\\{[\\s\\S]*?\\});\\n'));
  if (!m) throw new Error('Could not find ' + name + ' in plugin/code.js');
  return Function('return ' + m[1])();
}
const PRIMS = grab('PRIMS'), COLOR = grab('COLOR'), TYPE = grab('TYPE'), STYLES = grab('STYLES'), LAYOUT = grab('LAYOUT'), SH = grab('SH');

// ---------- helpers ----------
const set = (obj, p, val) => { const parts = p.split('/'); let o = obj; parts.slice(0, -1).forEach(k => o = o[k] = o[k] || {}); o[parts.at(-1)] = val; };
const dot = p => p.split('/').join('.');
const kebab = p => p.replace(/\//g, '-');
const write = (f, d) => { fs.writeFileSync(path.join(root, f), typeof d === 'string' ? d : JSON.stringify(d, null, 2) + '\n'); console.log('wrote', f); };
const WNUM = { light: 300, regular: 400, medium: 500, semibold: 600, bold: 700, extrabold: 800, black: 900 };
const weightNum = n => WNUM[n.split('/').pop()];
const famStack = name => /mono/i.test(name)
  ? `"${name}", ui-monospace, SFMono-Regular, Menlo, monospace`
  : `"${name}", system-ui, -apple-system, "Segoe UI", sans-serif`;

// ---------- JSON (DTCG) ----------
const prim = {};
for (const [n, type, v] of PRIMS) {
  if (type === 'COLOR') set(prim, n, { $type: 'color', $value: v });
  else if (n.startsWith('type/family/')) set(prim, n, { $type: 'fontFamily', $value: v });
  else if (n.startsWith('type/weight/')) set(prim, n, { $type: 'fontWeight', $value: weightNum(n) });
  else set(prim, n, { $type: 'dimension', $value: v + 'px' });
}
write('tokens/primitives.tokens.json', prim);

for (const [i, mode] of ['light', 'dark'].entries()) {
  const out = {};
  for (const [n, vals] of Object.entries(COLOR)) set(out, n, { $type: 'color', $value: `{color.${dot(vals[i])}}`, $description: vals[2] });
  write(`tokens/color.${mode}.tokens.json`, out);
}

const typeTypes = { FONT_FAMILY: 'fontFamily', FONT_WEIGHT: 'fontWeight', FONT_STYLE: 'fontWeight' };
const typeValue = (v, scope) => typeof v === 'string' && v.startsWith('prim:') ? `{${dot(v.slice(5))}}` : (scope === 'FONT_WEIGHT' || scope === 'FONT_STYLE' ? v : v + 'px');
for (const [i, mode] of ['desktop', 'mobile'].entries()) {
  const out = {};
  for (const [n, , scope, dv, mv, desc] of TYPE) {
    const tok = { $type: typeTypes[scope] || 'dimension', $value: typeValue(i ? mv : dv, scope) };
    if (desc) tok.$description = desc;
    set(out, 'typography/' + n, tok);
  }
  write(`tokens/typography.${mode}.tokens.json`, out);
}

const layout = {};
for (const [n, v, , desc] of LAYOUT) { const t = { $type: 'dimension', $value: v + 'px' }; if (desc) t.$description = desc; set(layout, n, t); }
write('tokens/layout.tokens.json', layout);

const shadows = {};
for (const [name, layers, desc] of SH) {
  set(shadows, 'shadow/' + name.split('/')[1].toLowerCase(), {
    $type: 'shadow', $description: desc,
    $value: layers.map(([x, y, blur, spread, tone]) => ({ color: `{shadow.neutral.${tone}}`, offsetX: x + 'px', offsetY: y + 'px', blur: blur + 'px', spread: spread + 'px' }))
  });
}
write('tokens/effects.tokens.json', shadows);

// ---------- CSS ----------
const P = '--ko-';
const L = [];
L.push('/* Kickoff UI — generated by scripts/build.js. Do not edit by hand. */', '');
L.push(':root {', '  /* Primitives */');
for (const [n, type, v] of PRIMS) {
  if (type === 'COLOR') L.push(`  ${P}${kebab(n)}: ${v};`);
  else if (n.startsWith('type/weight/')) L.push(`  ${P}${kebab(n)}: ${weightNum(n)};`);
  else if (n.startsWith('type/family/')) L.push(`  ${P}${kebab(n)}: ${famStack(v)};`);
  else L.push(`  ${P}${kebab(n)}: ${v}px;`);
}
L.push('', '  /* Layout */');
for (const [n, v] of LAYOUT) L.push(`  ${P}${kebab(n)}: ${v}px;`);
const typeVar = v => typeof v === 'string' && v.startsWith('prim:') ? `var(${P}${kebab(v.slice(5))})` : v + 'px';
L.push('', '  /* Typography (desktop) */');
for (const [n, , , dv] of TYPE) L.push(`  ${P}${kebab(n)}: ${typeVar(dv)};`);
const colorBlock = i => Object.entries(COLOR).map(([n, v]) => `  ${P}${kebab(n)}: var(${P}color-${kebab(v[i])});`);
L.push('', '  /* Color (light) */', ...colorBlock(0));
L.push('', '  /* Shadows */');
for (const [name, layers] of SH) L.push(`  ${P}shadow-${name.split('/')[1].toLowerCase()}: ${layers.map(([x, y, b, s, t]) => `${x}px ${y}px ${b}px ${s}px var(${P}shadow-neutral-${t})`).join(', ')};`);
L.push('}', '');
L.push('/* Dark mode: add data-theme="dark" to any element, or let it follow the system setting */');
L.push('[data-theme="dark"] {', ...colorBlock(1), '}', '');
L.push('@media (prefers-color-scheme: dark) {', '  :root:not([data-theme="light"]) {', ...colorBlock(1).map(l => '  ' + l), '  }', '}', '');
L.push('/* Mobile typography */', '@media (max-width: 767px) {', '  :root {');
for (const [n, , , dv, mv] of TYPE) if (JSON.stringify(dv) !== JSON.stringify(mv)) L.push(`    ${P}${kebab(n)}: ${typeVar(mv)};`);
L.push('  }', '}', '');
L.push('/* Text style classes, e.g. class="ko-body-md", "ko-body-md-emphasis" or "ko-body-md-strong" */');
for (const s of STYLES) {
  const [role, , emph] = s.name.split('/');
  const size = s.size.split('/')[1];
  const cls = `ko-${role.toLowerCase()}-${size}${emph === 'Default' ? '' : '-' + emph.toLowerCase()}`;
  L.push(`.${cls} { font-family: var(${P}${kebab(s.family)}); font-weight: var(${P}${kebab(s.weight)}); font-size: var(${P}${kebab(s.size)}); line-height: var(${P}${kebab(s.lh)}); letter-spacing: var(${P}${kebab(s.ls)}); }`);
}
write('css/kickoff-ui.css', L.join('\n') + '\n');
